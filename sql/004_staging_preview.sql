-- LOCAL PREPARATION ONLY: NOT EXECUTED. No CREATE/INSERT/MERGE/UPDATE/DELETE.
-- Preview a single validated source snapshot. Bind its SHA-256 as the parameter.
-- Source records must first pass Python validation and NUMBER(38,6) precision
-- checks. Do not use conversion alone as a substitute for those checks.
WITH typed AS (
  SELECT RECORD_HASH, SOURCE_SHA256, SOURCE_ROW_NUMBER,
    TO_NUMBER(REPLACE(TRIM("Year"), ','), 4, 0) AS YEAR,
    TO_NUMBER(TRIM("Quarter"), 1, 0) AS QUARTER,
    TO_DECIMAL(REPLACE(NULLIF(TRIM("Outgoing International Minutes Million"), ''), ','), 38, 6) AS OUTGOING_INTERNATIONAL_MINUTES_MILLION,
    TO_DECIMAL(REPLACE(NULLIF(TRIM("Incoming International Minutes Million"), ''), ','), 38, 6) AS INCOMING_INTERNATIONAL_MINUTES_MILLION,
    TO_DECIMAL(REPLACE(NULLIF(TRIM("Mobile Local Minutes Million"), ''), ','), 38, 6) AS MOBILE_LOCAL_MINUTES_MILLION,
    TO_DECIMAL(REPLACE(NULLIF(TRIM("Fixed Local Minutes Million"), ''), ','), 38, 6) AS FIXED_LOCAL_MINUTES_MILLION,
    TO_DECIMAL(REPLACE(NULLIF(TRIM("Fixed Broadband Consumption Million Gb"), ''), ','), 38, 6) AS FIXED_BROADBAND_CONSUMPTION_MILLION_GB,
    TO_DECIMAL(REPLACE(NULLIF(TRIM("Mobile Broadband Consumption Million Gb"), ''), ','), 38, 6) AS MOBILE_BROADBAND_CONSUMPTION_MILLION_GB,
    TO_DECIMAL(REPLACE(NULLIF(TRIM("International Internet Capacity Mbps"), ''), ','), 38, 6) AS INTERNATIONAL_INTERNET_CAPACITY_MBPS
  FROM {{DATABASE}}.RAW.TRA_TRAFFIC WHERE SOURCE_SHA256 = %s
)
SELECT RECORD_HASH, SOURCE_SHA256, YEAR, QUARTER,
       OUTGOING_INTERNATIONAL_MINUTES_MILLION, INCOMING_INTERNATIONAL_MINUTES_MILLION,
       MOBILE_LOCAL_MINUTES_MILLION, FIXED_LOCAL_MINUTES_MILLION,
       FIXED_BROADBAND_CONSUMPTION_MILLION_GB, MOBILE_BROADBAND_CONSUMPTION_MILLION_GB,
       INTERNATIONAL_INTERNET_CAPACITY_MBPS
FROM typed
QUALIFY ROW_NUMBER() OVER (PARTITION BY YEAR, QUARTER ORDER BY SOURCE_ROW_NUMBER) = 1;

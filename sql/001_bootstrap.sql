-- REVIEW AND OBTAIN APPROVAL BEFORE EXECUTION. {{DATABASE}} is rendered locally.
-- Use an approved existing role and warehouse. No role/warehouse/grant changes.
-- IF NOT EXISTS preserves existing definitions; it does not migrate them.
CREATE DATABASE IF NOT EXISTS {{DATABASE}};
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.RAW;
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.STAGING;
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.MART;
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.OPS;

-- For future prepared UTF-8 data files, NOT the original bilingual TRA export.
CREATE FILE FORMAT IF NOT EXISTS {{DATABASE}}.RAW.TRA_CSV_FORMAT
  TYPE = CSV FIELD_DELIMITER = ',' FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  SKIP_HEADER = 1 ENCODING = 'UTF8' EMPTY_FIELD_AS_NULL = TRUE
  NULL_IF = ('') ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;
CREATE FILE FORMAT IF NOT EXISTS {{DATABASE}}.RAW.TRA_JSON_FORMAT TYPE = JSON;
CREATE STAGE IF NOT EXISTS {{DATABASE}}.RAW.TRA_INGEST_STAGE
  FILE_FORMAT = (FORMAT_NAME = '{{DATABASE}}.RAW.TRA_JSON_FORMAT');

CREATE TABLE IF NOT EXISTS {{DATABASE}}.RAW.TRA_TRAFFIC (
  RECORD_HASH VARCHAR NOT NULL,
  SOURCE_SHA256 VARCHAR NOT NULL,
  SOURCE_ROW_NUMBER NUMBER(38,0) NOT NULL,
  FIRST_BATCH_ID VARCHAR NOT NULL,
  LOADED_AT TIMESTAMP_TZ NOT NULL,
  "Year" VARCHAR,
  "Quarter" VARCHAR,
  "Outgoing International Minutes Million" VARCHAR,
  "Incoming International Minutes Million" VARCHAR,
  "Mobile Local Minutes Million" VARCHAR,
  "Fixed Local Minutes Million" VARCHAR,
  "Fixed Broadband Consumption Million Gb" VARCHAR,
  "Mobile Broadband Consumption Million Gb" VARCHAR,
  "International Internet Capacity Mbps" VARCHAR
);


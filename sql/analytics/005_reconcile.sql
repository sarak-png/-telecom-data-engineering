SELECT COUNT(*) AS ROW_COUNT, MIN(YEAR) AS MIN_YEAR, MAX(YEAR) AS MAX_YEAR,
       COUNT(*) - COUNT(MOBILE_LOCAL_MIN_M) AS NULL_MOBILE_LOCAL_MIN_M,
       COUNT(*) - COUNT(FIXED_LOCAL_MIN_M) AS NULL_FIXED_LOCAL_MIN_M,
       COUNT(*) - COUNT(FIXED_BROADBAND_GB_M) AS NULL_FIXED_BROADBAND_GB_M,
       COUNT(*) - COUNT(MOBILE_BROADBAND_GB_M) AS NULL_MOBILE_BROADBAND_GB_M,
       COUNT(*) - COUNT(INTERNET_CAPACITY_MBPS) AS NULL_INTERNET_CAPACITY_MBPS
FROM TELECOM_DB.ANALYTICS.FACT_TELECOM_QUARTERLY;

SELECT YEAR, QUARTER, COUNT(*) AS COPIES
FROM TELECOM_DB.ANALYTICS.FACT_TELECOM_QUARTERLY
GROUP BY YEAR, QUARTER HAVING COUNT(*) > 1;

SELECT METRIC_NAME, SUM(OBSERVED_VALUE_COUNT) AS OBSERVED_CELLS,
       SUM(NULL_VALUE_COUNT) AS NULL_CELLS
FROM TELECOM_DB.ANALYTICS.VW_TELECOM_DATA_COVERAGE
GROUP BY METRIC_NAME ORDER BY METRIC_NAME;

SELECT * FROM TELECOM_DB.ANALYTICS.VW_YEARLY_TELECOM_SUMMARY WHERE YEAR = 2026;

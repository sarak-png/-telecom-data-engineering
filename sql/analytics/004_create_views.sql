CREATE VIEW TELECOM_DB.ANALYTICS.VW_YEARLY_TELECOM_SUMMARY AS
SELECT YEAR,
       COUNT(DISTINCT QUARTER) AS QUARTERS_PRESENT,
       MIN(QUARTER) AS FIRST_QUARTER_PRESENT,
       MAX(QUARTER) AS LAST_QUARTER_PRESENT,
       COUNT(DISTINCT QUARTER) = 4 AS IS_FULL_YEAR,
       MAX(CASE WHEN QUARTER = 4 THEN INTERNET_CAPACITY_MBPS END) AS Q4_INTERNET_CAPACITY_MBPS
FROM TELECOM_DB.ANALYTICS.FACT_TELECOM_QUARTERLY
GROUP BY YEAR;

CREATE VIEW TELECOM_DB.ANALYTICS.VW_TELECOM_DATA_COVERAGE AS
SELECT YEAR, METRIC_NAME,
       COUNT(DISTINCT QUARTER) AS QUARTERS_PRESENT,
       COUNT(METRIC_VALUE) AS OBSERVED_VALUE_COUNT,
       COUNT(*) - COUNT(METRIC_VALUE) AS NULL_VALUE_COUNT,
       4 AS EXPECTED_QUARTERS,
       4 - COUNT(DISTINCT QUARTER) AS ABSENT_QUARTER_COUNT,
       MAX(QUARTER) AS LATEST_QUARTER_PRESENT,
       COUNT(DISTINCT QUARTER) = 4 AND COUNT(METRIC_VALUE) = 4 AS IS_COMPLETE_YEAR
FROM TELECOM_DB.ANALYTICS.FACT_TELECOM_QUARTERLY
UNPIVOT INCLUDE NULLS (METRIC_VALUE FOR METRIC_NAME IN (
    OUTGOING_INT_MIN_M, INCOMING_INT_MIN_M, MOBILE_LOCAL_MIN_M,
    FIXED_LOCAL_MIN_M, FIXED_BROADBAND_GB_M, MOBILE_BROADBAND_GB_M,
    INTERNET_CAPACITY_MBPS
))
GROUP BY YEAR, METRIC_NAME;

SELECT COUNT(*) AS ROW_COUNT, MIN(YEAR) AS MIN_YEAR, MAX(YEAR) AS MAX_YEAR,
       COUNT(*) - COUNT(YEAR) AS NULL_YEAR_COUNT,
       COUNT(*) - COUNT(QUARTER) AS NULL_QUARTER_COUNT,
       COUNT(*) - COUNT(OUTGOING_INT_MIN_M) AS NULL_OUTGOING_INT_MIN_M,
       COUNT(*) - COUNT(INCOMING_INT_MIN_M) AS NULL_INCOMING_INT_MIN_M,
       COUNT(*) - COUNT(MOBILE_LOCAL_MIN_M) AS NULL_MOBILE_LOCAL_MIN_M,
       COUNT(*) - COUNT(FIXED_LOCAL_MIN_M) AS NULL_FIXED_LOCAL_MIN_M,
       COUNT(*) - COUNT(FIXED_BROADBAND_GB_M) AS NULL_FIXED_BROADBAND_GB_M,
       COUNT(*) - COUNT(MOBILE_BROADBAND_GB_M) AS NULL_MOBILE_BROADBAND_GB_M,
       COUNT(*) - COUNT(INTERNET_CAPACITY_MBPS) AS NULL_INTERNET_CAPACITY_MBPS
FROM TELECOM_DB.STAGING.TRA_TRAFFIC_CLEAN;

SELECT YEAR, QUARTER, COUNT(*) AS COPIES
FROM TELECOM_DB.STAGING.TRA_TRAFFIC_CLEAN
GROUP BY YEAR, QUARTER HAVING COUNT(*) > 1;

SELECT YEAR, QUARTER
FROM TELECOM_DB.STAGING.TRA_TRAFFIC_CLEAN
WHERE YEAR IS NULL OR QUARTER IS NULL
   OR YEAR NOT BETWEEN 2010 AND 2026 OR QUARTER NOT BETWEEN 1 AND 4;

SELECT YEAR, QUARTER, METRIC_NAME, METRIC_VALUE
FROM TELECOM_DB.STAGING.TRA_TRAFFIC_CLEAN
UNPIVOT INCLUDE NULLS (METRIC_VALUE FOR METRIC_NAME IN (
    OUTGOING_INT_MIN_M, INCOMING_INT_MIN_M, MOBILE_LOCAL_MIN_M,
    FIXED_LOCAL_MIN_M, FIXED_BROADBAND_GB_M, MOBILE_BROADBAND_GB_M,
    INTERNET_CAPACITY_MBPS
))
WHERE METRIC_VALUE < 0 OR METRIC_VALUE IN ('NaN'::FLOAT, 'inf'::FLOAT, '-inf'::FLOAT);

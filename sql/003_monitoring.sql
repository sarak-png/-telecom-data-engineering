-- Read-only review queries. Replace {{DATABASE}} with the approved identifier.
SELECT SOURCE_SHA256, COUNT(*) AS ROWS_LOADED,
       COUNT(DISTINCT RECORD_HASH) AS DISTINCT_RECORDS
FROM {{DATABASE}}.RAW.TRA_TRAFFIC GROUP BY SOURCE_SHA256;
SELECT RECORD_HASH, COUNT(*) AS COPIES FROM {{DATABASE}}.RAW.TRA_TRAFFIC
GROUP BY RECORD_HASH HAVING COUNT(*) > 1;
SELECT BATCH_ID, STATUS, EXPECTED_ROWS, INSERTED_ROWS, VERIFIED_ROWS,
       STARTED_AT, FINISHED_AT, ERROR_TYPE
FROM {{DATABASE}}.OPS.INGESTION_BATCHES ORDER BY STARTED_AT DESC;
